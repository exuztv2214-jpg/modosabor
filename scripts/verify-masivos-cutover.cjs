const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const app = fs.readFileSync(path.join(root, 'client', 'src', 'App.jsx'), 'utf8');
const launcher = fs.readFileSync(path.join(root, 'ModoSabor.pyw'), 'utf8');
const stitchServerPath = path.join(root, 'masivos', 'server.js');
const oldMasivosPath = path.join(root, 'client', 'src', 'pages', 'WhatsAppMasivo.jsx');
const stitchServer = fs.readFileSync(stitchServerPath, 'utf8');
const routeStart = app.indexOf('function MasivosPathRoutes()');
const routeEnd = app.indexOf('\nfunction SocialPathRoutes()', routeStart);
assert.ok(routeStart >= 0, 'No se encontró MasivosPathRoutes');
assert.ok(routeEnd > routeStart, 'No se pudo delimitar MasivosPathRoutes');
const route = app.slice(routeStart, routeEnd);

assert.match(app, /window\.location\.replace\('\/masivos'\)/);
assert.doesNotMatch(route, /<WhatsAppMasivo\s*\/>/);
assert.equal(fs.existsSync(oldMasivosPath), false);
assert.match(stitchServer, /const PORT = Number\(process\.env\.PORT \|\| 3867\)/);
assert.match(stitchServer, /const HOST = process\.env\.HOST \|\| ['"]127\.0\.0\.1['"]/);
assert.match(stitchServer, /MASIVOS_PROXY_TOKEN/);
assert.match(stitchServer, /MASIVOS_BASE_PATH/);
const mainServer = fs.readFileSync(path.join(root, 'server', 'index.js'), 'utf8');
assert.match(mainServer, /MASIVOS_UPSTREAM_URL/);
assert.match(mainServer, /x-masivos-proxy-token/);
assert.match(mainServer, /marketing\.edit/);
assert.match(launcher, /PROMO_ROOT\s*=\s*BASE_DIR\s*\/\s*["']masivos["']/);
assert.doesNotMatch(launcher, /D:\\\\ModoSaborPromoStitch/);
assert.doesNotMatch(launcher, /0\/2/);
assert.match(launcher, /PROMO_ROOT/);
assert.match(launcher, /PROMO_LOCK/);
assert.match(launcher, /panel\.lock\.json/);
assert.match(launcher, /WHATSAPP_DISABLE_STARTUP/);
assert.match(launcher, /api\/status/);
assert.match(launcher, /"stitch"/);
assert.match(launcher, /for port in \(5173, 3001, 3867\)/);
assert.match(launcher, /str\(PROMO_SERVER\)/);
assert.match(launcher, /self\.write_pid\("stitch",/);

console.log('Masivos cutover estático: OK');
